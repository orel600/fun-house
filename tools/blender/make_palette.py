# 8 הראשונות זהות ל-palette.png של מחקר הכובעים (research/own-models), ועוד 8 לשמיים ולכוכבים.
# palette_weapons.png הוא הצבע, ו-palette_weapons_glow.png הוא הזוהר: שחור חוץ מהעמודות שזוהרות.
