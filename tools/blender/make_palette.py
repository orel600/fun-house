import sys
from PIL import Image
COLS=[  # שם, למעלה, אמצע, למטה, זוהר?
 ('iron',(192,202,212),(132,141,153),(74,82,96),0),('darkiron',(117,121,131),(78,81,90),(41,43,51),0),
 ('bone',(250,241,219),(213,197,168),(178,155,119),0),('gold',(254,232,136),(234,177,82),(215,124,30),0),
 ('leather',(176,120,78),(132,84,52),(86,52,34),0),('purple',(160,110,210),(112,70,170),(70,40,120),0),
 ('blue',(110,160,230),(60,110,200),(30,60,140),0),('red',(230,100,90),(190,50,50),(120,30,40),0),
 ('sky',(246,252,255),(120,196,255),(46,104,214),0),        # קשת השמיים: לבן בקצה, תכלת, כחול ליד הידית
 ('navy',(92,96,170),(54,58,124),(28,28,74),0),             # ידית ומוט: כחול לילה
 ('violet',(176,140,240),(120,84,200),(66,40,134),0),
 ('glowc',(240,255,255),(170,240,255),(90,200,255),1),      # אור תכלת: מיתר, גבישים, טבעת
 ('glowy',(255,253,226),(255,234,130),(255,190,60),1),      # אור כוכב: צהוב-לבן
 ('white',(255,255,255),(226,234,246),(184,196,220),0),
 ('pink',(255,190,230),(255,111,181),(190,60,140),1),
 ('deep',(60,90,180),(36,56,140),(20,26,80),0),
 ('oak',(222,158,98),(166,104,60),(96,58,32),0),            # מטה האלון: עץ חם
 ('leaf',(170,232,120),(86,178,72),(38,112,46),0),          # עלים
 ('stone',(222,220,206),(164,162,150),(98,98,94),0),        # פטיש השומר: אבן
 ('moss',(186,222,96),(118,168,58),(62,108,40),0),          # טחב
 ('rune',(214,255,200),(120,245,130),(40,196,90),1)]        # רונה ירוקה זוהרת
def lerp(a,b,t):return tuple(int(a[i]+(b[i]-a[i])*t) for i in range(3))
W,H,CW=256,64,8   # 32 עמודות (חזקה של 2, מקום לעוד), העמודות שלא בשימוש שחורות
col=Image.new('RGB',(W,H));glo=Image.new('RGB',(W,H))
for c,(n,top,mid,bot,g) in enumerate(COLS):
    for y in range(H):
        t=y/(H-1);p=lerp(top,mid,t*2) if t<0.5 else lerp(mid,bot,(t-0.5)*2)
        for x in range(c*CW,(c+1)*CW):col.putpixel((x,y),p);glo.putpixel((x,y),p if g else (0,0,0))
col.save(sys.argv[1]+'/palette_weapons.png');glo.save(sys.argv[1]+'/palette_weapons_glow.png')
print(' '.join(f'{n}={i}' for i,(n,*_ ) in enumerate(COLS)))
