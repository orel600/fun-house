MX, MY, MW = 40, 52, 920
SC = MW / W
def P(x, y): return (MX + (x + W/2) * SC, MY + (y + H/2) * SC)

def smooth(pts):
    n = len(pts); s = ''
    for i in range(n):
        p0, p1, p2, p3 = pts[i-1], pts[i], pts[(i+1) % n], pts[(i+2) % n]
        if i == 0: s += 'M%.1f,%.1f ' % p1
        c1 = (p1[0] + (p2[0]-p0[0])/6, p1[1] + (p2[1]-p0[1])/6)
        c2 = (p2[0] - (p3[0]-p1[0])/6, p2[1] - (p3[1]-p1[1])/6)
        s += 'C%.1f,%.1f %.1f,%.1f %.1f,%.1f ' % (c1 + c2 + p2)
    return s + 'Z'

def blob(cx, cy, rx, ry, seed=1, n=14, wob=0.18):
    out = []
    for i in range(n):
        a = 2*math.pi*i/n
        k = 1 + wob*math.sin(seed*1.7 + i*2.3) * math.cos(seed*0.9 + i*1.1)
        out.append((cx + rx*k*math.cos(a), cy + ry*k*math.sin(a)))
    return out

def inpoly(x, y, pts):
    c = False; n = len(pts)
    for i in range(n):
        x1, y1 = pts[i]; x2, y2 = pts[(i+1) % n]
        if (y1 > y) != (y2 > y) and x < (x2-x1)*(y-y1)/(y2-y1) + x1: c = not c
    return c

def segd(px, py, a, b):
    (x1, y1), (x2, y2) = a, b; dx, dy = x2-x1, y2-y1
    t = max(0, min(1, ((px-x1)*dx + (py-y1)*dy) / (dx*dx + dy*dy or 1)))
    return math.hypot(px-x1-t*dx, py-y1-t*dy)

